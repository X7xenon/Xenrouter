"""
Lightweight mock inference server for end-to-end integration testing.
Simulates an OpenAI-compatible local engine (vLLM / llama-server / LM Studio)
with API key validation, streaming SSE generation, and rate limiting simulation.
"""

import asyncio
import json
import time
from fastapi import FastAPI, Header, HTTPException, Request
from fastapi.responses import JSONResponse, StreamingResponse
import uvicorn

app = FastAPI(title="MockLocalInference")

VALID_KEYS = {"sk-test-alpha", "sk-test-beta", "sk-test-gamma"}
CALL_COUNT = 0


@app.get("/v1/models")
async def list_models():
    return {
        "object": "list",
        "data": [
            {"id": "qwen2.5-coder:14b", "object": "model", "owned_by": "mock"},
            {"id": "llama3.2:3b", "object": "model", "owned_by": "mock"},
            {"id": "deepseek-r1:14b", "object": "model", "owned_by": "mock"}
        ]
    }


@app.post("/v1/chat/completions")
async def chat_completions(request: Request, authorization: str = Header(None)):
    global CALL_COUNT
    CALL_COUNT += 1

    # Validate Authorization Key
    if not authorization or not authorization.startswith("Bearer "):
        raise HTTPException(status_code=401, detail="Missing or malformed Authorization header")

    token = authorization.split("Bearer ", 1)[1].strip()
    if token not in VALID_KEYS:
        raise HTTPException(status_code=403, detail="Forbidden: Invalid local API key")

    # Simulate rate-limit on a specific key to test key rotation
    if token == "sk-test-alpha" and CALL_COUNT % 2 == 1:
        raise HTTPException(status_code=429, detail="Simulated 429 Rate Limit for key alpha")

    body = await request.json()
    model = body.get("model", "unknown")
    stream = body.get("stream", False)

    if stream:
        async def event_generator():
            words = ["Local", "inference", "via", "Xenrouter", "is", "active", "and", "ultra", "fast."]
            for word in words:
                chunk = {
                    "id": "chatcmpl-mock",
                    "object": "chat.completion.chunk",
                    "created": int(time.time()),
                    "model": model,
                    "choices": [{"delta": {"content": f" {word}"}, "index": 0, "finish_reason": None}]
                }
                yield f"data: {json.dumps(chunk)}\n\n".encode("utf-8")
                await asyncio.sleep(0.02)
            yield b"data: [DONE]\n\n"

        return StreamingResponse(event_generator(), media_type="text/event-stream")

    return JSONResponse({
        "id": "chatcmpl-mock",
        "object": "chat.completion",
        "created": int(time.time()),
        "model": model,
        "choices": [{
            "index": 0,
            "message": {"role": "assistant", "content": f"Response generated by mock engine for model {model} using key {token[:7]}."},
            "finish_reason": "stop"
        }],
        "usage": {
            "prompt_tokens": 15,
            "completion_tokens": 18,
            "total_tokens": 33
        }
    })


if __name__ == "__main__":
    uvicorn.run(app, host="127.0.0.1", port=18080, log_level="error")
